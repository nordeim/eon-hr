import { chromium } from "@playwright/test";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto("http://127.0.0.1:3200/login");
await page.fill('input[type=email]', "sepnetflix2023@outlook.com");
await page.fill('input[type=password]', "$Abcd1234");
await page.getByRole("button", { name: "Sign in" }).click();
await page.waitForURL("http://127.0.0.1:3200/", { timeout: 15000 });
await page.goto("http://127.0.0.1:3200/recruitment");
await page.getByRole("tab", { name: "AI CV Upload" }).waitFor({ timeout: 10000 });
const before = await page.locator('[role=tab]').evaluateAll((els) => els.map((e) => ({ name: e.textContent?.trim(), selected: e.getAttribute("aria-selected") })));
console.log("before:", JSON.stringify(before));
await page.getByRole("tab", { name: "AI CV Upload" }).click();
await page.waitForTimeout(2000);
const after = await page.locator('[role=tab]').evaluateAll((els) => els.map((e) => ({ name: e.textContent?.trim(), selected: e.getAttribute("aria-selected") })));
console.log("after:", JSON.stringify(after));
const visibleCombo = await page.locator('[role=combobox]:visible').count();
console.log("visible comboboxes:", visibleCombo);
await browser.close();
