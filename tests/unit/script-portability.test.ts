import { describe, expect, it } from "vitest";
import { execSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { extractTextFromFile } from "@/lib/cv-text";

// Session 120 (D-120a): THE SCRIPT-PORTABILITY CONTRACT — the fresh-clone
// reproducibility pin (the neo-crm s210 checkout-portability genus). The
// r116-r119 census scripts imported their prototype copies from /tmp —
// ephemeral sandbox state the reset deletes — leaving `tsc` AND
// `next build` RED on any fresh clone (23 unresolved imports). The cure:
// the committed census proto (scripts/protos/cv-text-proto.ts = the real
// source + exactly two documented insertions, regenerated by
// scripts/protos/sync-proto.mjs) and the repo-relative imports.
describe("script portability — the census proto contract (session 120, D-120a)", () => {
  const root = join(import.meta.dirname, "..", "..");
  const listTs = (dir: string): string[] =>
    execSync(`find ${join(root, dir)} -name "*.ts" -not -path "*/node_modules/*"`, { encoding: "utf8" })
      .split("\n")
      .filter(Boolean);

  it("bans the ephemeral /tmp module imports from every script (the ban arm)", () => {
    // a census script that imports sandbox-local state breaks the
    // fresh-clone gates — every module reference must resolve inside the
    // repo (or a real dependency)
    const offenders: string[] = [];
    for (const f of [...listTs("scripts"), ...listTs("tests")]) {
      const src = readFileSync(f, "utf8");
      if (/await\s+import\(\s*["']\/tmp\//.test(src) || /require\(\s*["']\/tmp\//.test(src) || /from\s+["']\/tmp\//.test(src)) {
        offenders.push(f.replace(root + "/", ""));
      }
    }
    expect(offenders).toEqual([]); // ← RED at HEAD: the 23 r116-r119 census scripts
  });

  it("keeps the committed proto exactly equal to the source plus its two insertions (the sync arm)", () => {
    // the proto must never drift from src/lib/cv-text.ts: regenerate the
    // expected content with the sync script's exact anchors and compare
    const src = readFileSync(join(root, "src", "lib", "cv-text.ts"), "utf8");
    const proto = readFileSync(join(root, "scripts", "protos", "cv-text-proto.ts"), "utf8");
    const ANCHOR_EXPORT = "const MAX_INFLATED_BYTES = 8 * 1024 * 1024;";
    const EXPORT_BLOCK = `

// R120-A: THE FLAT DEBUG SURFACE — the committed proto's module-level
// addition over src/lib/cv-text.ts (see scripts/protos/PROTO.md). The
// r117 census family reads mod.__r117DebugPieces after an extraction; the
// capture hook (insertion 2, at the decoded map) appends each part's
// pieces. The app NEVER imports this file — census scripts only.
export const __r117DebugPieces: Array<Record<string, unknown>> = [];`;
    const ANCHOR_HOOK = "    // R110-D: the census is SPACE-only";
    const HOOK_BLOCK = `    // R120-A: THE DEBUG-CAPTURE HOOK — the committed proto's in-body
    // addition over src/lib/cv-text.ts (see scripts/protos/PROTO.md).
    // Each part's decoded pieces feed the census surfaces: __r119pages
    // (the nested per-part form), __r118pieces (the flat spread form),
    // and the module-level __r117DebugPieces export. The census scripts
    // reset their own global before each extraction; the hook only
    // ever appends — the extraction's own output is untouched.
    {
      const __g = globalThis as unknown as { __r119pages?: unknown[][]; __r118pieces?: unknown[] };
      (__g.__r119pages ??= []).push(decoded);
      const __flat = decoded.map((d) => {
        const e = d as unknown as { p: Record<string, unknown>; text: string; genuine?: boolean; trail?: boolean };
        return { ...e.p, text: e.text, genuine: e.genuine, trail: e.trail };
      });
      (__g.__r118pieces ??= []).push(...__flat);
      __r117DebugPieces.push(...__flat);
    }
`;
    expect(src).toContain(ANCHOR_EXPORT);
    expect(src).toContain(ANCHOR_HOOK);
    const expected = src
      .replace(ANCHOR_EXPORT, ANCHOR_EXPORT + EXPORT_BLOCK)
      .replace(ANCHOR_HOOK, HOOK_BLOCK + ANCHOR_HOOK);
    expect(proto).toBe(expected); // ← RED at HEAD: the proto does not exist
  });

  it("exposes the census surfaces on a real extraction (the surface arm)", async () => {
    // the proto's debug-capture hook populates the three census surfaces
    // the scripts/ families read — the fixture smoke
    const proto = await import(/* @vite-ignore */ join(root, "scripts", "protos", "cv-text-proto.ts"));
    const g = globalThis as unknown as { __r119pages?: unknown[][]; __r118pieces?: unknown[] };
    g.__r119pages = [];
    g.__r118pieces = [];
    (proto as unknown as { __r117DebugPieces: unknown[] }).__r117DebugPieces.length = 0;
    const content = "BT /F1 12 Tf (payrollcompliancetrainingonboardingspecialist platform) Tj ET";
    const deflated = new Uint8Array(
      await new Response(new Blob([content]).stream().pipeThrough(new CompressionStream("deflate"))).arrayBuffer()
    );
    const head = new TextEncoder().encode("1 0 obj\n<< /Filter /FlateDecode /Length " + deflated.length + " >>\nstream\r\n");
    const tail = new TextEncoder().encode("\r\nendstream\nendobj\ntrailer\n<< /Root 1 0 R >>\n%%EOF");
    const pdf = new Uint8Array(head.length + deflated.length + tail.length);
    pdf.set(head, 0);
    pdf.set(deflated, head.length);
    pdf.set(tail, head.length + deflated.length);
    const text = await (proto as typeof import("@/lib/cv-text")).extractTextFromFile(
      new File([pdf], "resume.pdf", { type: "application/pdf" })
    );
    expect(text).toContain("payrollcompliance");
    expect((g.__r119pages ?? []).length).toBeGreaterThan(0); // the nested per-part surface
    expect((g.__r118pieces ?? []).length).toBeGreaterThan(0); // the flat spread surface
    expect((proto as unknown as { __r117DebugPieces: unknown[] }).__r117DebugPieces.length).toBeGreaterThan(0); // the module export
    // the extraction output is UNTOUCHED by the hook (the proto equals the
    // source's behavior)
    expect(await extractTextFromFile(new File([pdf], "resume.pdf", { type: "application/pdf" }))).toBe(text);
  });
});
